import { createClient } from "npm:@supabase/supabase-js@2";

const SUPABASE_URL = Deno.env.get("SUPABASE_URL") ?? "";
const SERVICE_ROLE_KEY = Deno.env.get("SUPABASE_SERVICE_ROLE_KEY") ?? "";
const GEMINI_API_KEY = Deno.env.get("GEMINI_API_KEY") ?? "";
const GOOGLE_CLIENT_ID = Deno.env.get("GOOGLE_CLIENT_ID") ?? "";
const GOOGLE_CLIENT_SECRET = Deno.env.get("GOOGLE_CLIENT_SECRET") ?? "";
const GOOGLE_REFRESH_TOKEN = Deno.env.get("GOOGLE_REFRESH_TOKEN") ?? "";
const GOOGLE_REDIRECT_URI = Deno.env.get("GOOGLE_REDIRECT_URI") ?? `${SUPABASE_URL}/functions/v1/email-admin/google/callback`;
const GEMINI_MODEL = Deno.env.get("GEMINI_MODEL") ?? "gemini-1.5-flash";
const admin = createClient(SUPABASE_URL, SERVICE_ROLE_KEY, { auth: { autoRefreshToken: false, persistSession: false } });

function cors(req: Request) {
  const origin = req.headers.get("Origin") || "";
  const allowed = origin.endsWith(".workers.dev") || origin.endsWith(".vercel.app") || origin.endsWith(".figma.site") || /^http:\/\/(localhost|127\.0\.0\.1)(:\d+)?$/.test(origin);
  return { "Access-Control-Allow-Origin": allowed ? origin : "https://bca-vault.portalbcavault.workers.dev", "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type", "Access-Control-Allow-Methods": "GET, POST, OPTIONS", "Content-Type": "application/json" };
}
function json(req: Request, body: unknown, status = 200) { return new Response(JSON.stringify(body), { status, headers: cors(req) }); }
function esc(v: unknown) { return String(v ?? "").replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;").replaceAll('"', "&quot;").replaceAll("'", "&#39;"); }

async function requireAdmin(req: Request) {
  const token = req.headers.get("Authorization")?.replace(/^Bearer\s+/i, "");
  if (!token) throw new Error("Authentication required.");
  const { data: { user }, error } = await admin.auth.getUser(token);
  if (error || !user) throw new Error("Authentication required or expired.");
  const { data: profile } = await admin.from("admin_profiles").select("user_id,role,status").eq("user_id", user.id).eq("status", "active").maybeSingle();
  if (!profile || !["admin", "superadmin"].includes(profile.role)) throw new Error("Admin access required.");
  return user;
}

function factsFor(eventType: string, p: Record<string, unknown>) {
  const student = esc(p.student_name ?? p.referrer_name ?? "Student");
  const course = esc(p.course ?? "BCA");
  const semester = esc(p.semester ?? "");
  const bundle = esc(p.bundle_name ?? "BCA Vault Bundle");
  const amount = esc(p.amount ?? "");
  const ref = esc(p.reference_last4 ? `••••${p.reference_last4}` : "");
  const note = esc(p.admin_note ?? "");
  if (eventType === "payment_approved") return `Student: ${student}\nCourse: ${course}\nSemester: ${semester}\nBundle: ${bundle}\nAmount: ₹${amount}\nReference: ${ref}\nStatus: Approved`;
  if (eventType === "payment_rejected") return `Student: ${student}\nCourse: ${course}\nSemester: ${semester}\nBundle: ${bundle}\nReference: ${ref}\nStatus: Rejected\nReview note: ${note}`;
  if (eventType === "referral_reward_unlocked") return `Referrer: ${student}\nReferred student: ${esc(p.referred_student_name ?? "Student")}\nReward: Most Repeated Topics — Foundation of Computing, C Programming, HTML + CSS + JavaScript`;
  throw new Error(`Unsupported email event type: ${eventType}`);
}

async function generateEmail(eventType: string, payload: Record<string, unknown>) {
  if (!GEMINI_API_KEY) throw new Error("GEMINI_API_KEY is not configured.");
  const models = [
    "gemini-3.6-flash",
    "gemini-3.1-pro-preview",
    "gemini-3.0-pro",
    "gemini-2.0-flash",
    "gemini-1.5-flash-latest"
  ];

  const prompt = `You write professional transactional emails for BCA Vault, an Indian BCA study platform. Generate ONE concise, natural, human-sounding email. Do not invent facts, links, prices, dates, promises, or policies. Preserve all supplied facts. Tone: warm, professional, clear. Avoid saying the email was generated by AI. Return valid JSON only with keys subject, text, html. The html must be a complete email body fragment, not markdown, safe for Gmail, with simple inline styles. The text must be plain text.\n\nEvent: ${eventType}\nFacts:\n${factsFor(eventType, payload)}`;

  const errors: Record<string, string> = {};
  for (const model of models) {
    try {
      const r = await fetch(
        `https://generativelanguage.googleapis.com/v1beta/models/${encodeURIComponent(model)}:generateContent?key=${encodeURIComponent(GEMINI_API_KEY)}`,
        {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({
            contents: [{ role: "user", parts: [{ text: prompt }] }],
            generationConfig: { temperature: 0.35, responseMimeType: "application/json" },
          }),
        }
      );
      const d = await r.json().catch(() => ({}));
      if (!r.ok) {
        errors[model] = d?.error?.message || `HTTP ${r.status}`;
        continue;
      }
      const raw = d?.candidates?.[0]?.content?.parts?.map((x: any) => x.text || "").join("") || "";
      let parsed: any;
      try {
        parsed = JSON.parse(raw);
      } catch {
        parsed = JSON.parse(raw.replace(/^```json\s*/i, "").replace(/\s*```$/i, ""));
      }
      if (!parsed?.subject || !parsed?.text || !parsed?.html) {
        errors[model] = "Incomplete response";
        continue;
      }
      return {
        subject: String(parsed.subject).trim(),
        text_body: String(parsed.text).trim(),
        html_body: String(parsed.html).trim(),
      };
    } catch (e: any) {
      errors[model] = e?.message || String(e);
    }
  }
  throw new Error("Gemini generation failed: " + JSON.stringify(errors));
}

function base64url(bytes: Uint8Array) { let binary = ""; for (let i = 0; i < bytes.length; i += 0x8000) binary += String.fromCharCode(...bytes.subarray(i, Math.min(i + 0x8000, bytes.length))); return btoa(binary).replaceAll("+", "-").replaceAll("/", "_").replace(/=+$/g, ""); }
function mimeHeader(v: string) { return `=?UTF-8?B?${btoa(unescape(encodeURIComponent(v)))}?=`; }
function makeRaw(fromEmail: string, subject: string, text: string, html: string, to: string) { const boundary = `bca_${crypto.randomUUID().replaceAll("-", "")}`; const body = [`From: BCA Vault <${fromEmail}>`, `To: ${to}`, `Subject: ${mimeHeader(subject)}`, `MIME-Version: 1.0`, `Content-Type: multipart/alternative; boundary="${boundary}"`, ``, `--${boundary}`, `Content-Type: text/plain; charset="UTF-8"`, `Content-Transfer-Encoding: 8bit`, ``, text, ``, `--${boundary}`, `Content-Type: text/html; charset="UTF-8"`, `Content-Transfer-Encoding: 8bit`, ``, html, ``, `--${boundary}--`].join("\r\n"); return base64url(new TextEncoder().encode(body)); }

async function googleAccessToken() {
  if (!GOOGLE_CLIENT_ID || !GOOGLE_CLIENT_SECRET || !GOOGLE_REFRESH_TOKEN) throw new Error("Google Gmail OAuth credentials are not configured.");
  const r = await fetch("https://oauth2.googleapis.com/token", { method: "POST", headers: { "Content-Type": "application/x-www-form-urlencoded" }, body: new URLSearchParams({ client_id: GOOGLE_CLIENT_ID, client_secret: GOOGLE_CLIENT_SECRET, refresh_token: GOOGLE_REFRESH_TOKEN, grant_type: "refresh_token" }) });
  const d = await r.json().catch(() => ({}));
  if (!r.ok || !d.access_token) throw new Error(d?.error_description || d?.error || `Google OAuth HTTP ${r.status}`);
  return String(d.access_token);
}
async function gmailProfile(token: string) {
  try {
    const r = await fetch("https://gmail.googleapis.com/gmail/v1/users/me/profile", { headers: { Authorization: `Bearer ${token}` } });
    const d = await r.json().catch(() => ({}));
    if (r.ok && d.emailAddress) return String(d.emailAddress);
  } catch {}
  return Deno.env.get("EMAIL_FROM_ADDRESS") || "bcavault07@gmail.com";
}

Deno.serve(async (req) => {
  if (req.method === "OPTIONS") return new Response("ok", { status: 200, headers: cors(req) });
  try {
    const rawPath = new URL(req.url).pathname;
    const path = rawPath
      .replace(/^\/functions\/v1\/email-admin/, "")
      .replace(/^\/email-admin/, "")
      .replace(/\/$/, "") || "/";

    // OAuth bootstrap/callback MUST remain public. These routes intentionally do not call requireAdmin().
    if (path === "/google/start" && req.method === "GET") {
      if (!GOOGLE_CLIENT_ID || !GOOGLE_CLIENT_SECRET) return new Response("Google OAuth client credentials are not configured.", { status: 500 });
      const params = new URLSearchParams({ client_id: GOOGLE_CLIENT_ID, redirect_uri: GOOGLE_REDIRECT_URI, response_type: "code", access_type: "offline", prompt: "consent", scope: "https://www.googleapis.com/auth/gmail.send" });
      return Response.redirect(`https://accounts.google.com/o/oauth2/v2/auth?${params.toString()}`, 302);
    }
    if (path === "/google/callback" && req.method === "GET") {
      const error = new URL(req.url).searchParams.get("error");
      if (error) return new Response(`Google OAuth failed: ${error}`, { status: 400 });
      const code = new URL(req.url).searchParams.get("code");
      if (!code) return new Response("Google OAuth failed: missing code.", { status: 400 });
      const r = await fetch("https://oauth2.googleapis.com/token", { method: "POST", headers: { "Content-Type": "application/x-www-form-urlencoded" }, body: new URLSearchParams({ code, client_id: GOOGLE_CLIENT_ID, client_secret: GOOGLE_CLIENT_SECRET, redirect_uri: GOOGLE_REDIRECT_URI, grant_type: "authorization_code" }) });
      const d = await r.json().catch(() => ({}));
      if (!r.ok || !d.refresh_token) return new Response(`Google OAuth failed: ${d?.error_description || d?.error || "No refresh token returned"}`, { status: 400 });
      return new Response(`OAuth complete. Copy this refresh token into the Supabase Edge Function secret GOOGLE_REFRESH_TOKEN:\n\n${d.refresh_token}\n`, { headers: { "Content-Type": "text/plain; charset=utf-8" } });
    }

    const user = await requireAdmin(req);
    const body = await req.json().catch(() => ({}));

    if (path === "/verify-gmail" && req.method === "POST") {
      try {
        const token = await googleAccessToken();
        const from = await gmailProfile(token);
        return json(req, { success: true, from });
      } catch (err: any) {
        return json(req, { success: false, error: err.message }, 400);
      }
    }
    if (path === "/list" && req.method === "POST") {
      const { data, error } = await admin.from("email_outbox").select("id,event_key,event_type,recipient_user_id,recipient_email,sender_name,status,subject,html_body,text_body,generated_at,generated_by,approved_at,approved_by,attempt_count,last_error,provider_message_id,created_at,sent_at,failed_at,payload").order("created_at", { ascending: false }).limit(100);
      if (error) throw new Error(error.message);
      return json(req, { success: true, data });
    }
    if (path === "/generate" && req.method === "POST") {
      const id = String(body.id || "");
      if (!id) return json(req, { success: false, error: "Email job ID is required." }, 400);
      const { data: job, error: fetchError } = await admin.from("email_outbox").select("*").eq("id", id).single();
      if (fetchError || !job) return json(req, { success: false, error: "Email job not found." }, 404);
      if (job.status === "sent") return json(req, { success: false, error: "This email has already been sent." }, 409);
      const draft = await generateEmail(job.event_type, job.payload ?? {});
      const { data, error } = await admin.from("email_outbox").update({ ...draft, generated_at: new Date().toISOString(), generated_by: user.id, approved_at: null, approved_by: null, status: "pending", locked_at: null, last_error: null }).eq("id", id).select("*").single();
      if (error) throw new Error(error.message);
      return json(req, { success: true, data });
    }
    if (path === "/save" && req.method === "POST") {
      const id = String(body.id || ""); const subject = String(body.subject || "").trim(); const html = String(body.html_body || "").trim(); const text = String(body.text_body || "").trim();
      if (!id || !subject || !html || !text) return json(req, { success: false, error: "ID, subject, HTML body and text body are required." }, 400);
      const { data, error } = await admin.from("email_outbox").update({ subject, html_body: html, text_body: text, generated_at: new Date().toISOString(), generated_by: user.id, approved_at: new Date().toISOString(), approved_by: user.id, status: "pending", locked_at: null, last_error: null }).eq("id", id).neq("status", "sent").select("*").single();
      if (error || !data) throw new Error(error?.message || "Email could not be saved.");
      return json(req, { success: true, data });
    }
    if (path === "/send" && req.method === "POST") {
      const id = String(body.id || ""); if (!id) return json(req, { success: false, error: "Email job ID is required." }, 400);
      const { data: claimed, error: claimError } = await admin.from("email_outbox").update({ status: "processing", locked_at: new Date().toISOString(), approved_at: new Date().toISOString(), approved_by: user.id }).eq("id", id).eq("status", "pending").select("*").single();
      if (claimError || !claimed) return json(req, { success: false, error: "Email is not ready to send, or it was already sent/claimed." }, 409);
      if (!claimed.subject || !claimed.html_body || !claimed.text_body) { await admin.from("email_outbox").update({ status: "pending", locked_at: null, last_error: "Generate and save the email before sending." }).eq("id", id); return json(req, { success: false, error: "Generate and save the email before sending." }, 400); }
      try {
        const token = await googleAccessToken(); const from = await gmailProfile(token); const raw = makeRaw(from, claimed.subject, claimed.text_body, claimed.html_body, claimed.recipient_email);
        const r = await fetch("https://gmail.googleapis.com/gmail/v1/users/me/messages/send", { method: "POST", headers: { Authorization: `Bearer ${token}`, "Content-Type": "application/json" }, body: JSON.stringify({ raw }) });
        const d = await r.json().catch(() => ({})); if (!r.ok || !d.id) throw new Error(d?.error?.message || `Gmail HTTP ${r.status}`);
        const now = new Date().toISOString(); await admin.from("email_delivery_log").insert({ outbox_id: id, user_id: claimed.recipient_user_id, recipient_email: claimed.recipient_email, event_type: claimed.event_type, provider: "gmail", provider_message_id: d.id, status: "sent", sent_at: now });
        const { data: sentRow } = await admin.from("email_outbox").update({ status: "sent", sent_at: now, locked_at: null, last_error: null, provider_message_id: d.id }).eq("id", id).select("*").single();
        return json(req, { success: true, data: sentRow, provider_message_id: d.id });
      } catch (err) {
        const message = err instanceof Error ? err.message : String(err); const now = new Date().toISOString();
        await admin.from("email_delivery_log").insert({ outbox_id: id, user_id: claimed.recipient_user_id, recipient_email: claimed.recipient_email, event_type: claimed.event_type, provider: "gmail", status: "failed", failed_at: now, error_message: message });
        await admin.from("email_outbox").update({ status: "failed", failed_at: now, locked_at: null, last_error: message }).eq("id", id);
        return json(req, { success: false, error: message }, 502);
      }
    }
    return json(req, { success: false, error: "Not found." }, 404);
  } catch (err) { return json(req, { success: false, error: err instanceof Error ? err.message : String(err) }, 500); }
});
